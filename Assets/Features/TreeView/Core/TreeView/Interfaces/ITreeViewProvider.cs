using System;
using System.Collections.Generic;
using Core.TreeView.Models;

namespace Core.TreeView.Interfaces
{
    /// <summary>
    /// Интерфейс для провайдера данных дерева (TreeView).
    /// Определяет контракт для компонентов, которые предоставляют данные для отображения в виде дерева.
    /// 
    /// ИСПОЛЬЗОВАНИЕ:
    /// - Реализуется DatabaseTreeViewProvider для работы с базой данных
    /// - Используется TreeViewController для получения данных
    /// - Позволяет абстрагироваться от конкретной реализации источника данных
    /// 
    /// СВЯЗИ:
    /// - TreeViewController: использует для получения данных и управления состоянием
    /// - DatabaseTreeViewProvider: основная реализация для работы с БД
    /// - ITreeNode: предоставляет узлы для отображения
    /// 
    /// ОСНОВНЫЕ ВОЗМОЖНОСТИ:
    /// - Управление корневым узлом дерева
    /// - Получение видимых узлов с поддержкой пагинации
    /// - Управление состоянием развернутости узлов
    /// - Выбор и отмена выбора узлов
    /// - Обновление состояния дерева
    /// - Уведомление о загрузке данных
    /// </summary>
    public interface ITreeViewProvider
    {
        /// <summary>
        /// Корневой узел дерева
        /// Точка входа в иерархию данных
        /// 
        /// ВОЗВРАЩАЕТ:
        /// - Корневой узел дерева
        /// </summary>
        ITreeNode Root { get; }

        /// <summary>
        /// Событие, вызываемое после загрузки данных
        /// Используется для уведомления UI о готовности данных к отображению
        /// 
        /// ПРИМЕР ИСПОЛЬЗОВАНИЯ:
        /// - TreeViewController подписывается на это событие для обновления отображения
        /// - DatabaseTreeViewProvider вызывает при завершении загрузки данных с сервера
        /// </summary>
        event Action OnDataLoaded;

        /// <summary>
        /// Возвращает список видимых узлов (root не включается)
        /// Основной метод для получения данных для отображения
        /// 
        /// ВОЗВРАЩАЕТ:
        /// - Список видимых узлов для отображения в UI
        /// 
        /// ПРИМЕЧАНИЕ:
        /// - Корневой узел не включается в результат
        /// - Может применяться фильтрация по правам доступа
        /// </summary>
        List<ITreeNode> GetVisibleNodes();

        /// <summary>
        /// Получить страницу видимых узлов (для пагинации по корню дерева)
        /// Используется для отображения части узлов при большом количестве
        /// 
        /// ПАРАМЕТРЫ:
        /// - start: начальный индекс (начиная с 0)
        /// - count: количество узлов для получения
        /// 
        /// ВОЗВРАЩАЕТ:
        /// - Список узлов для указанной страницы
        /// 
        /// ПРИМЕЧАНИЕ:
        /// - Если start выходит за границы, возвращается пустой список
        /// - Если count больше доступного количества, возвращаются все оставшиеся узлы
        /// </summary>
        List<ITreeNode> GetVisibleNodesPage(int start, int count);

        /// <summary>
        /// Получить общее количество видимых узлов (для пагинации по корню дерева)
        /// Используется для вычисления общего количества страниц
        /// 
        /// ВОЗВРАЩАЕТ:
        /// - Общее количество видимых узлов
        /// 
        /// ПРИМЕЧАНИЕ:
        /// - Корневой узел не учитывается в подсчете
        /// </summary>
        int GetVisibleNodesCount();

        /// <summary>
        /// Разворачивает узел
        /// Делает дочерние элементы узла видимыми
        /// 
        /// ПАРАМЕТРЫ:
        /// - node: узел для разворачивания
        /// 
        /// ПРИМЕЧАНИЕ:
        /// - Для FieldTreeNode может запускаться асинхронная загрузка значений
        /// - Узел добавляется в список развернутых узлов
        /// </summary>
        void ExpandNode(ITreeNode node);

        /// <summary>
        /// Сворачивает узел
        /// Скрывает дочерние элементы узла
        /// 
        /// ПАРАМЕТРЫ:
        /// - node: узел для сворачивания
        /// 
        /// ПРИМЕЧАНИЕ:
        /// - Узел удаляется из списка развернутых узлов
        /// - Состояние развернутости сохраняется для восстановления
        /// </summary>
        void CollapseNode(ITreeNode node);

        /// <summary>
        /// Выбирает узел
        /// Снимает выбор с предыдущего узла и выбирает новый
        /// 
        /// ПАРАМЕТРЫ:
        /// - node: узел для выбора
        /// 
        /// ПРИМЕЧАНИЕ:
        /// - Только один узел может быть выбран одновременно
        /// - Предыдущий выбранный узел автоматически снимается
        /// </summary>
        void SelectNode(ITreeNode node);

        /// <summary>
        /// Отменяет выбор узла
        /// Снимает выбор с указанного узла
        /// 
        /// ПАРАМЕТРЫ:
        /// - node: узел для отмены выбора
        /// 
        /// ПРИМЕЧАНИЕ:
        /// - Если узел не был выбран, ничего не происходит
        /// </summary>
        void DeselectNode(ITreeNode node);

        /// <summary>
        /// Обновляет состояние дерева
        /// Восстанавливает развернутые узлы и выбранный узел
        /// 
        /// ПРИМЕЧАНИЕ:
        /// - Используется после перезагрузки данных
        /// - Восстанавливает состояние из внутренних коллекций
        /// </summary>
        void Refresh();
    }
} 