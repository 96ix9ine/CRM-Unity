using System.Collections.Generic;

namespace Core.TreeView.Models
{
    /// <summary>
    /// Интерфейс для узла дерева (TreeView).
    /// Определяет базовую структуру узла с поддержкой иерархии, состояния и данных.
    /// 
    /// ИСПОЛЬЗОВАНИЕ:
    /// - Базовый интерфейс для всех типов узлов в дереве
    /// - Реализуется TreeNode для базовой функциональности
    /// - Расширяется DatabaseTreeNode для работы с базой данных
    /// - Используется TreeViewController для отображения
    /// 
    /// СВЯЗИ:
    /// - TreeNode: базовая реализация интерфейса
    /// - DatabaseTreeNode: специализированная реализация для БД
    /// - TreeViewController: использует для отображения и управления
    /// - ITreeViewProvider: предоставляет узлы для отображения
    /// 
    /// ОСНОВНЫЕ ВОЗМОЖНОСТИ:
    /// - Уникальная идентификация узла
    /// - Иерархическая структура с дочерними элементами
    /// - Состояние развернутости и выбора
    /// - Дополнительные данные узла
    /// </summary>
    public interface ITreeNode
    {
        /// <summary>
        /// Уникальный идентификатор узла
        /// Используется для идентификации узла в дереве
        /// 
        /// ПРИМЕЧАНИЕ:
        /// - Должен быть уникальным в рамках всего дерева
        /// - Используется для поиска узлов и управления состоянием
        /// </summary>
        int Id { get; }

        /// <summary>
        /// Отображаемое имя узла
        /// Используется для отображения в UI
        /// 
        /// ПРИМЕЧАНИЕ:
        /// - Может быть локализованным названием
        /// - Для специализированных узлов может содержать дополнительную информацию
        /// </summary>
        string Name { get; }

        /// <summary>
        /// Дочерние узлы
        /// Определяет иерархическую структуру дерева
        /// 
        /// ПРИМЕЧАНИЕ:
        /// - Листовые узлы имеют пустой список
        /// - Может изменяться динамически (например, при ленивой загрузке)
        /// - Используется для рекурсивного обхода дерева
        /// </summary>
        List<ITreeNode> Children { get; }

        /// <summary>
        /// Флаг развернутости узла
        /// Определяет, отображаются ли дочерние элементы
        /// 
        /// ПРИМЕЧАНИЕ:
        /// - true: дочерние элементы видимы
        /// - false: дочерние элементы скрыты
        /// - Используется для управления отображением в UI
        /// </summary>
        bool IsExpanded { get; set; }

        /// <summary>
        /// Флаг выбора узла
        /// Определяет, выбран ли узел пользователем
        /// 
        /// ПРИМЕЧАНИЕ:
        /// - true: узел выбран (подсвечен в UI)
        /// - false: узел не выбран
        /// - Обычно только один узел может быть выбран одновременно
        /// </summary>
        bool IsSelected { get; set; }

        /// <summary>
        /// Дополнительные данные узла
        /// Может содержать любые данные, связанные с узлом
        /// 
        /// ПРИМЕЧАНИЕ:
        /// - Может быть null
        /// - Для DatabaseTreeNode содержит данные строки из БД
        /// - Используется для передачи контекстной информации
        /// </summary>
        object Data { get; set; }

        /// <summary>
        /// Добавляет дочерний узел
        /// Расширяет иерархическую структуру дерева
        /// 
        /// ПАРАМЕТРЫ:
        /// - child: дочерний узел для добавления
        /// 
        /// ПРИМЕЧАНИЕ:
        /// - Узел добавляется в конец списка дочерних элементов
        /// - Может изменять состояние развернутости родителя
        /// </summary>
        void AddChild(ITreeNode child);

        /// <summary>
        /// Удаляет дочерний узел
        /// Сокращает иерархическую структуру дерева
        /// 
        /// ПАРАМЕТРЫ:
        /// - child: дочерний узел для удаления
        /// 
        /// ВОЗВРАЩАЕТ:
        /// - true, если узел был найден и удален
        /// - false, если узел не найден
        /// 
        /// ПРИМЕЧАНИЕ:
        /// - Удаляет только прямого потомка
        /// - Не удаляет вложенные узлы рекурсивно
        /// </summary>
        bool RemoveChild(ITreeNode child);

        /// <summary>
        /// Очищает все дочерние узлы
        /// Удаляет всю иерархию под текущим узлом
        /// 
        /// ПРИМЕЧАНИЕ:
        /// - Удаляет всех прямых потомков
        /// - Вложенные узлы удаляются автоматически
        /// - Узел становится листовым
        /// </summary>
        void ClearChildren();

        int CurrentPage { get; set; }
        int ItemsPerPage { get; set; }
        int GetTotalPages();
        List<ITreeNode> GetPageChildren();
    }
} 